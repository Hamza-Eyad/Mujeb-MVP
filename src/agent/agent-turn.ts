import { AsyncQueue, abortReason, sleep } from '../core/async.js';
import { ProviderError } from '../core/errors.js';
import type { LanguageModel, LlmEvent, LlmRequest, ToolExchange, ToolResult, ToolSpec } from '../ports/language-model.js';
import type { Conversation } from './conversation.js';
import type { ToolCallResult, ToolTurnContext } from './tools/appointment-tools.js';

/**
 * One user turn with tools: model round → tool calls → model round … until the model answers in text.
 * Knows nothing about audio. Runs as its own task so the session can stop listening to it (barge-in)
 * while work that must finish — a confirmed write — still completes and is recorded.
 *
 * Limits: at most `maxToolRounds` rounds may call tools; the next round must answer in text
 * (`toolChoice: none`). Each round has a first-event timeout. New tool calls never start once the turn
 * is cancelled; a data-changing call waits `mutationGraceMs` first, so a caller who keeps talking
 * cancels it before anything changes.
 *
 * Authoritative speech: when a tool result carries `speech` (a read-back to confirm, or a write's result),
 * the turn speaks those exact words itself and ends — the model gets no further round in which it could
 * reword a date or time. It sees the words in the tool output and in the history afterwards.
 */

/** What the session needs from a set of tools (implemented by AppointmentTools). */
export interface AgentToolbox {
  definitions(): readonly ToolSpec[];
  execute(name: string, rawArguments: string, turn: ToolTurnContext): Promise<ToolCallResult>;
  /** True for tools that change data in an external system. */
  mutates(name: string): boolean;
  /** Extra per-request instructions (e.g. the current date and time). */
  contextNote(): string;
  /** `heardText`: what the caller actually heard of the turn (played audio), when known. */
  onTurnFinalized(turnId: string, heardAnything: boolean, heardText?: string): void;
  reconcileUnresolved(): Promise<readonly { action_ref: string; kind: string; applied: boolean }[]>;
  drain(timeoutMs: number): Promise<number>;
}

/** Text for the caller, or `pause`: the model now waits on a tool, so speak what you have. */
export type AgentOutput = { type: 'text'; text: string } | { type: 'pause' };

export interface AgentToolEvent {
  phase: 'start' | 'end';
  round: number;
  name: string;
  callId: string;
  outcome?: string;
  ms?: number;
}

export interface AgentTurnOptions {
  llm: LanguageModel;
  conversation: Conversation;
  tools: AgentToolbox;
  /** The caller's words for this turn (STT) — also what confirmations are checked against. */
  userText: string;
  userTurn: number;
  turnId: string;
  signal: AbortSignal;
  maxToolRounds: number;
  firstEventTimeoutMs: number;
  mutationGraceMs: number;
  /**
   * Said once, before the first tool runs, when the model has said nothing yet in this turn — so the caller
   * does not wait in silence through several tool rounds (measured live: up to ~4.5 s without it).
   */
  waitPhrase?: string;
  /** Extra context for this turn only (e.g. outcomes of earlier writes that were just reconciled). */
  notes?: readonly string[];
  onLlmRequest?: (round: number) => void;
  onLlmFirstEvent?: (round: number) => void;
  onTool?: (event: AgentToolEvent) => void;
}

export interface ToolCallSummary {
  name: string;
  outcome: string;
  ms: number;
}

export class AgentTurn {
  readonly output = new AsyncQueue<AgentOutput>();
  /** Finished tool rounds of this turn, in order (each call with its result). */
  readonly exchanges: ToolExchange[] = [];
  readonly toolCalls: ToolCallSummary[] = [];
  rounds = 0;
  toolsMs = 0;
  /** A data-changing tool started executing in this turn. */
  sideEffects = false;
  /** The turn has produced words for the caller (model text or the wait phrase). */
  private saidAnything = false;
  /** Authoritative words the turn spoke on behalf of a tool (never generated by the model). */
  readonly systemSpeech: string[] = [];
  /** Settles when every model round and tool call has finished. Never rejects. */
  readonly done: Promise<void>;
  finished = false;
  private readonly o: AgentTurnOptions;

  constructor(options: AgentTurnOptions) {
    this.o = options;
    this.done = this.run().finally(() => {
      this.finished = true;
    });
  }

  private async run(): Promise<void> {
    const { signal } = this.o;
    try {
      const definitions = this.o.tools.definitions();
      const context = [this.o.tools.contextNote(), ...(this.o.notes ?? [])].join('\n');
      for (let round = 0; !signal.aborted; round += 1) {
        const mayCallTools = round < this.o.maxToolRounds;
        const request = this.o.conversation.request(this.o.userText, {
          currentTurn: this.exchanges,
          tools: definitions,
          toolChoice: mayCallTools ? 'auto' : 'none',
          context,
        });
        this.rounds = round + 1;
        this.o.onLlmRequest?.(round);
        const completion = await this.streamRound(request, round);
        const calls = mayCallTools ? (completion.toolCalls ?? []) : [];
        if (calls.length === 0) break;

        if (!this.saidAnything && this.o.waitPhrase !== undefined && this.o.waitPhrase.trim() !== '') {
          this.output.push({ type: 'text', text: this.o.waitPhrase });
          this.saidAnything = true;
        }
        this.output.push({ type: 'pause' });
        const results: ToolResult[] = [];
        const speech: string[] = [];
        for (const call of calls) {
          if (signal.aborted) break;
          const mutates = this.o.tools.mutates(call.name);
          if (mutates && this.o.mutationGraceMs > 0) {
            // The caller may still be talking ("yes… but"): give the turn a moment to be cancelled first.
            try {
              await sleep(this.o.mutationGraceMs, signal);
            } catch {
              break;
            }
          }
          if (mutates) this.sideEffects = true;
          const ran = await this.runTool(call, round);
          results.push(ran.result);
          if (ran.speech !== undefined) speech.push(ran.speech);
        }
        const answered = calls.filter((c) => results.some((r) => r.callId === c.callId));
        if (answered.length > 0) {
          const complete = answered.length === calls.length;
          this.exchanges.push({
            type: 'tool_exchange',
            calls: answered,
            results,
            // A partial round cannot be replayed verbatim (its provider items mention unanswered calls).
            ...(complete && completion.continuation ? { continuation: completion.continuation } : {}),
          });
        }
        if (speech.length > 0 && !signal.aborted) {
          // Authoritative words: spoken exactly as the tool built them, and the turn ends here.
          this.systemSpeech.push(...speech);
          this.output.push({ type: 'text', text: speech.join(' ') });
          break;
        }
      }
      if (signal.aborted) this.output.fail(abortReason(signal));
      else this.output.end();
    } catch (err) {
      this.output.fail(signal.aborted ? abortReason(signal) : err);
    }
  }

  private async streamRound(request: LlmRequest, round: number): Promise<Extract<LlmEvent, { type: 'completed' }>> {
    const timeout = new AbortController();
    const timer = setTimeout(
      () => timeout.abort(new ProviderError(this.o.llm.name, 'timeout', `No model output within ${this.o.firstEventTimeoutMs}ms`)),
      this.o.firstEventTimeoutMs,
    );
    let first = true;
    try {
      for await (const event of this.o.llm.stream(request, { signal: AbortSignal.any([this.o.signal, timeout.signal]) })) {
        if (first) {
          first = false;
          clearTimeout(timer);
          this.o.onLlmFirstEvent?.(round);
        }
        if (event.type === 'completed') return event;
        if (event.text.trim() !== '') this.saidAnything = true;
        this.output.push({ type: 'text', text: event.text });
      }
      throw new ProviderError(this.o.llm.name, 'bad_response', 'Model stream ended without completion');
    } catch (err) {
      if (timeout.signal.aborted && !this.o.signal.aborted) throw abortReason(timeout.signal);
      throw err;
    } finally {
      clearTimeout(timer);
    }
  }

  /** Runs one call. Reads end early if the turn is cancelled (that rejection ends the turn); confirmed writes complete. */
  private async runTool(call: { callId: string; name: string; arguments: string }, round: number): Promise<{ result: ToolResult; speech?: string }> {
    this.o.onTool?.({ phase: 'start', round, name: call.name, callId: call.callId });
    const started = performance.now();
    const result = await this.o.tools.execute(call.name, call.arguments, {
      userTurn: this.o.userTurn,
      callerUtterance: this.o.userText,
      turnId: this.o.turnId,
      signal: this.o.signal,
    });
    const ms = Math.round((performance.now() - started) * 10) / 10;
    this.toolsMs += ms;
    this.toolCalls.push({ name: call.name, outcome: result.outcome, ms });
    this.o.onTool?.({ phase: 'end', round, name: call.name, callId: call.callId, outcome: result.outcome, ms });
    return { result: { callId: call.callId, output: JSON.stringify(result.output) }, ...(result.speech !== undefined ? { speech: result.speech } : {}) };
  }
}
